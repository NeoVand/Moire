section('data/ablation.json : one mechanism removed, time relative to full');
const abl = load('ablation.json');
{
  const COLS = [
    ['tri.', 'triangle rot+off @1'],
    ['hex.\\ out', 'hexagon rot+off @0.15'],
    ['near $s$', 'square rot+off, offset near spacing @1'],
    ['marginal', 'triangle translated, marginal drift @1'],
  ];
  const ROWS = [
    ['Lipschitz skip (\\S\\ref{sec:skip})', 'no Lipschitz skip'],
    ['Support fast paths (\\S\\ref{sec:walking})', 'no support fast path'],
    ['Exact drift (\\S\\ref{sec:drift})', 'loose drift bound'],
    ['Polygon closed form (\\S\\ref{sec:closed})', 'no polygon closed form'],
    ['Carried rotation (\\S\\ref{sec:skip})', 'no carried rotation'],
    ['Accept early exit (\\S\\ref{sec:guard})', 'no accept exit'],
  ];
  const rel = (sceneKey, mech) => {
    const scene = abl[sceneKey];
    if (!scene) throw new Error(`ablation.json has no scene "${sceneKey}"`);
    if (!scene[mech]) throw new Error(`ablation.json has no "${mech}" for "${sceneKey}"`);
    // A patch that no longer matches the source records an error rather than a
    // time. Publishing around it would quietly drop a row from the table.
    if (scene[mech].error) {
      throw new Error(
        `ablation.json: "${mech}" on "${sceneKey}" did not run: ${scene[mech].error}. ` +
          `Re-run paper/tools/gpu/ablation.mjs after repairing the patch.`
      );
    }
    // Prefer the paired ratio when the data carries one: each of its repeats has
    // its own baseline measured beside it, so it is free of the drift that a
    // quotient of two separately reduced times would inherit.
    return scene[mech].ratio ?? scene[mech].passMs / scene.full.passMs;
  };

  // Two things this table cannot be trusted without, both learned the hard way.
  // Table 3 and Table 6 are both GPU measurements, and Section 8.1 names a single
  // adapter for both. If they come from different machines that sentence is wrong
  // about one of them, and the two tables cannot be read against each other.
  if (abl.device?.adapter && gpu.meta?.adapter) {
    const same =
      abl.device.adapter.vendor === gpu.meta.adapter.vendor &&
      abl.device.adapter.architecture === gpu.meta.adapter.architecture;
    if (!same) {
      throw new Error(
        `ablation.json was measured on ${abl.device.adapter.vendor}/${abl.device.adapter.architecture} ` +
          `but gpu.json on ${gpu.meta.adapter.vendor}/${gpu.meta.adapter.architecture}. ` +
          `\u00a78.1 names one adapter for both tables. Re-run tools/gpu/run.mjs and ` +
          `tools/gpu/ablation.mjs on the same machine.`
      );
    }
  }

  if (abl.worstSecondOverMin === undefined) {
    console.warn(
      '  WARNING: ablation.json predates the current tools/gpu/ablation.mjs and ' +
        'carries no floor check. Re-run tools/gpu/ablation.mjs.'
    );
  } else if (abl.worstSecondOverMin > 0.15) {
    // Every cell is a quotient of two floors, each the fastest of several passes,
    // since contention only ever adds time. This asks whether those fastest passes
    // were flukes: if a second pass reached the same floor, the floor is the
    // machine's and not an accident of scheduling.
    throw new Error(
      `ablation.json: some floor was reached only once -- the second-fastest pass ` +
        `was ${pc(abl.worstSecondOverMin)}% above it. Re-run tools/gpu/ablation.mjs ` +
        `with nothing else using the GPU.`
    );
  }
  // Two decimals reads well below 10; a 90x entry does not need them.
  const fmt = (v) => (v >= 10 ? r(v, 1) : r(v, 2));

  const skip = COLS.map(([, key]) => rel(key, 'no Lipschitz skip')).filter((v) => v > 1.001);
  macro('ablSkipLo', r(minOf(skip), 1));
  macro('ablSkipHi', r(maxOf(skip), 1));
  macro('ablClosedMarginal', fmt(rel('triangle translated, marginal drift @1', 'no polygon closed form')));
  const cheaper = ['no carried rotation', 'no accept exit']
    .flatMap((m) => COLS.map(([, key]) => rel(key, m)))
    .filter((v) => v < 0.999);
  macro('ablCostLo', Math.round((1 - maxOf(cheaper)) * 100));
  macro('ablCostHi', Math.round((1 - minOf(cheaper)) * 100));
  macro('ablMpixel', r(abl.megapixels, 2));

  const rows = ROWS.map(([label, mech]) => {
    const vals = COLS.map(([, key]) => rel(key, mech));
    const worst = maxOf(vals);
    return (
      `    ${label} & ` +
      vals
        .map((v) => (v === worst && worst >= 10 ? `$\\mathbf{${fmt(v)}}$` : `$${fmt(v)}$`))
        .join(' & ') +
      ' \\\\'
    );
  });
  writeFileSync(
    new URL('tab-ablation.tex', PAPER),
    `% GENERATED by paper/tools/numbers.mjs
\\begin{table}[t]
  \\centering
  \\small
  \\caption{Time relative to the full method when one mechanism is removed
  ($${r(abl.megapixels, 2)}$\\,Mpixel of solver work). Each column is a different family, chosen so
  that every mechanism has a column where it binds. Values below $1$ mean the
  mechanism costs time in that setting, which is the price of exactness
  elsewhere.}
  \\label{tab:ablation}
  \\begin{tabular}{lcccc}
    \\toprule
     & \\multicolumn{2}{c}{rotated} & \\multicolumn{2}{c}{translated} \\\\
    \\cmidrule(lr){2-3}\\cmidrule(lr){4-5}
    Mechanism removed & ${COLS.map(([l]) => l).join(' & ')} \\\\
    \\midrule
${rows.join('\n')}
    \\bottomrule
  \\end{tabular}
\\end{table}
`
  );
}

