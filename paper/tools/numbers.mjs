// Regenerate numbers.tex and the generated tables from data/.
//
// Every figure the prose quotes comes from here, so the text cannot drift from
// the experiments. Run after any experiment changes:
//
//   node paper/tools/numbers.mjs

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { ENVELOPE_TAPS, PATTERN_META } from '../../src/types/moire.ts';
import { FIELD_PRESETS } from '../../src/fields/expr.ts';

const DATA = new URL('../data/', import.meta.url);
const PAPER = new URL('../', import.meta.url);

// A missing data file is a failure, not a silent fallback: the paper claims its
// numbers are generated, so a half-generated numbers.tex must not build.
const load = (name) => {
  const url = new URL(name, DATA);
  if (!existsSync(url)) {
    throw new Error(
      `data/${name} is missing. Run the experiment that writes it (see paper/README.md) ` +
        `before regenerating numbers.tex.`
    );
  }
  return JSON.parse(readFileSync(url, 'utf8'));
};

const out = [];
const macro = (name, value) => out.push(`\\newcommand{\\${name}}{${value}}`);
const section = (title) => out.push('', `% ---- ${title}`);
const r = (v, n = 2) => Number(v).toFixed(n);
/** Percent from a fraction. */
const pc = (v, n = 1) => r(Number(v) * 100, n);
/** Thousands separators LaTeX can typeset inside math. */
const th = (v) => Math.round(Number(v)).toLocaleString('en-US').replace(/,/g, '{,}');
const minOf = (xs) => Math.min(...xs);
const maxOf = (xs) => Math.max(...xs);

out.push(
  '% GENERATED by paper/tools/numbers.mjs -- do not edit by hand.',
  '% Every number the prose quotes, in one place, so text and data cannot drift.'
);

